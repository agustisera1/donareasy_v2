CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  AS $function$BEGIN
  -- Crear el usuario en public.users con el mismo ID y email
  INSERT INTO public.users (id, email, is_active, created_at, onboarding_complete)
  VALUES (
    NEW.id,
    NEW.email,
    true, -- Por defecto activo
    NOW(),
    false -- Onboarding no completado
  );

  RETURN NEW;
END;$function$;

